local function clickButton(button)

    -- 3. Simulation du clic universel (compatible TextButton / Activated)
    if button and getconnections then
        for _, connection in ipairs(getconnections(button.MouseButton1Click)) do
            connection:Fire()
        end
        for _, connection in ipairs(getconnections(button.MouseButton1Down)) do
            connection:Fire()
        end
        for _, connection in ipairs(getconnections(button.Activated)) do
            connection:Fire()
        end
        print("[UI] Clic automatique sur le bouton Play effectué.")
    end
end

